#!/usr/bin/env python3
"""Write tests/golden/prompts_verify.json: hash and length of the three constants of the checking pass (M7 P1,
EXPERIMENTAL): VERIFY_SYSTEM, VERIFY_PROMPT and VERIFY_PROMPT_CARDS. Hashes and lengths only. The constants come from
kafka_sre_rag/prompts.py and are no part of frozen.json; when their text is changed on purpose, run this script in the
same change (a changed check prompt means a new pilot).
Run from the repository root: .venv/bin/python tests/golden/make_golden_verify.py [out.json]
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kafka_sre_rag import prompts as P  # noqa: E402

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("prompts_verify.json")


def h(s):
    return {"sha256": hashlib.sha256(s.encode("utf-8")).hexdigest(), "len": len(s)}


out = {"_note": "hashes and lengths only; generated by tests/golden/make_golden_verify.py from kafka_sre_rag/prompts.py",
       "VERIFY_SYSTEM": h(P.VERIFY_SYSTEM), "VERIFY_PROMPT": h(P.VERIFY_PROMPT),
       "VERIFY_PROMPT_CARDS": h(P.VERIFY_PROMPT_CARDS)}
OUT.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
print(f"wrote {OUT}")
