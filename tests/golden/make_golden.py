#!/usr/bin/env python3
"""Capture the Phase 0 prompt hashes from the ORIGINAL code (pre-refactor) without importing mlx_lm.

Method: scripts/rag_answers.py is parsed with ast (never imported or executed); STRICT, THOROUGH and
pack_text are exec'd from their source segments, and the inline user-message expressions inside main()
are evaluated from their source segments. build_dataset and retrieve (no mlx) are imported by path.
Only valid on the pre-refactor sources; the result is the contract in tests/golden/prompts_phase0.json.
Run from the repository root: .venv/bin/python tests/golden/make_golden.py [out.json]
"""
import ast, hashlib, importlib.util, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKS, INDEX = ROOT / "work/v3/rag_packs_base_exp.json", ROOT / "work/v2/chunks.jsonl"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("prompts_phase0.json")


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[name] = m
    spec.loader.exec_module(m)
    return m


def h(s):
    return {"sha256": hashlib.sha256(s.encode("utf-8")).hexdigest(), "len": len(s)}


sys.path.insert(0, str(ROOT / "scripts"))
BD, RT = load("build_dataset", ROOT / "scripts/build_dataset.py"), load("retrieve", ROOT / "scripts/retrieve.py")
src = (ROOT / "scripts/rag_answers.py").read_text()
tree = ast.parse(src)
ns = {"index": RT.index, "CHUNKS": RT.CHUNKS, "THOROUGH": None, "STRICT": None}
for n in tree.body:
    if isinstance(n, ast.Assign) and n.targets[0].id in ("STRICT", "THOROUGH") or isinstance(n, ast.FunctionDef) and n.name == "pack_text":
        exec(compile(ast.Module([n], []), "rag_answers", "exec"), ns)
main = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "main")
user_expr = thorough_expr = None
for n in ast.walk(main):
    if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "user" and isinstance(n.value, ast.Tuple | ast.BinOp):
        user_expr = ast.get_source_segment(src, n.value)
    if isinstance(n, ast.AugAssign) and getattr(n.target, "id", "") == "user":
        thorough_expr = ast.get_source_segment(src, n.value)
assert user_expr and thorough_expr, "inline user message not found"


class A:  # stands in for the argparse namespace
    def __init__(s, strict=False, index=None):
        s.strict, s.index = strict, index


def user(q, ids, strict=False, thorough=False):
    a, packs = A(strict, str(INDEX)), {q: ids}
    u = eval(user_expr, ns, {"a": a, "packs": packs, "q": q})
    return u + eval(thorough_expr, ns) if thorough else u


rows = json.load(open(PACKS))
out = {"_note": "hashes and lengths only; generated by tests/golden/make_golden.py from pre-refactor code",
       "system_prompt": h(BD.SYSTEM_PROMPT), "expand_system": h(RT.EXPAND_SYSTEM), "questions": {}}
for i, r in enumerate(rows, 1):
    q = r["question"]
    out["questions"][str(i)] = {
        "user_k6": h(user(q, r["k6"])), "user_k3": h(user(q, r["k3"])),
        "user_k6_strict": h(user(q, r["k6"], strict=True)), "user_k6_thorough": h(user(q, r["k6"], thorough=True)),
        "pack_k6": h(ns["pack_text"](r["k6"], str(INDEX))), "pack_k3": h(ns["pack_text"](r["k3"], str(INDEX))),
    }
OUT.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
print(f"wrote {OUT} ({len(rows)} questions)")
