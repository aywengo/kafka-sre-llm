#!/usr/bin/env python3
"""Write tests/golden/prompts_grounded.json: hash and length of the two grounded constants (GROUNDED_G1, GROUNDED_G2)
and, for the 40 legacy k6 packs, the hash of the grounded user messages (INSTRUCTION, pack, question, grounded text).
Hashes and lengths only. The constants come from kafka_sre_rag/prompts.py; when the Owner changes the text, run this
script (and update prompts_sha256 in kafka_sre_rag/frozen.json to the same values) in the same change.
Run from the repository root: .venv/bin/python tests/golden/make_golden_grounded.py [out.json]
The per-question part needs work/v3/rag_packs_base_exp.json and work/v2/chunks.jsonl (git-ignored); without them
only the constants are written and the script says so.
"""
import hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kafka_sre_rag import prompts as P  # noqa: E402

PACKS, INDEX = ROOT / "work/v3/rag_packs_base_exp.json", ROOT / "work/v2/chunks.jsonl"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("prompts_grounded.json")


def h(s):
    return {"sha256": hashlib.sha256(s.encode("utf-8")).hexdigest(), "len": len(s)}


out = {"_note": "hashes and lengths only; generated by tests/golden/make_golden_grounded.py from kafka_sre_rag/prompts.py",
       "GROUNDED_G1": h(P.GROUNDED_G1), "GROUNDED_G2": h(P.GROUNDED_G2), "questions": {}}
if PACKS.exists() and INDEX.exists():
    by_id = {}
    for line in open(INDEX):
        c = json.loads(line)
        by_id[c["id"]] = c
    rows = json.load(open(PACKS))
    for i, r in enumerate(rows, 1):
        k6 = [by_id[x] for x in r["k6"]]
        out["questions"][str(i)] = {
            "user_k6_grounded_g1": h(P.grounded_user_message(r["question"], k6, "grounded-g1")),
            "user_k6_grounded_g2": h(P.grounded_user_message(r["question"], k6, "grounded-g2"))}
else:
    print("work/ packs absent: per-question hashes not written", file=sys.stderr)
OUT.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
print(f"wrote {OUT} ({len(out['questions'])} questions)")
